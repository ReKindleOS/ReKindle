#!/usr/bin/env node
/*
 * Build js/home-deps.js: the five local scripts the home screen needs before
 * it can paint (time.js, icons.js, icons-beta.js, js/ui-kit.js, js/ip-ban.js)
 * concatenated into one request. Keeping the source files separate means every
 * other page still loads only what it needs; this bundle is homepage-only.
 *
 * Run `npm run build:home-deps` after changing any of the inputs, then bump
 * `?v=` on the bundle in index.html and sw.js.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const FILES = [
    'time.js',
    'icons.js',
    'icons-beta.js',
    'js/ui-kit.js',
    'js/ip-ban.js'
];

function build() {
    let out = '/* GENERATED by scripts/build-home-deps.js - do not edit. */\n';
    for (const file of FILES) {
        const body = fs.readFileSync(path.join(ROOT, file), 'utf8');
        out += '\n/* ---- ' + file + ' ---- */\n' + body.replace(/\s+$/, '') + '\n';
    }
    return out;
}

if (require.main === module) {
    const target = path.join(ROOT, 'js/home-deps.js');
    fs.writeFileSync(target, build());
    console.log('wrote ' + path.relative(ROOT, target) + ' (' + Buffer.byteLength(build()) + ' bytes)');
}

module.exports = { build, FILES };
