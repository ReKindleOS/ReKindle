'use strict';

/*
 * Writes the SEO head block and the screen-reader <h1> into every page.
 *
 * Run: node scripts/seo-inject.js          (writes in place)
 *      node scripts/seo-inject.js --check  (reports drift, exit 1)
 *
 * The metadata itself lives in scripts/seo-pages.js. This file only renders it,
 * so re-running is safe: the generated region is delimited by
 * `<!-- seo:begin` / `<!-- seo:end -->` and replaced wholesale.
 *
 * What goes in
 *   - meta description, robots, canonical (self-referencing, absolute)
 *   - Open Graph + Twitter card tags (the site had none, so every share showed
 *     a bare link)
 *   - JSON-LD: WebApplication + BreadcrumbList (WebSite on the home page)
 *   - <h1> when the page has no heading with text (the app name lives in a
 *     title-bar <span>, which carries no heading semantics for crawlers or
 *     screen readers)
 *
 * Why the canonical points at rekindle.ink on every build: lite.rekindle.ink and
 * legacy.rekindle.ink are the same pages rendered for older browsers, and
 * /x.html, /X and /x/ all resolve to the same document. One canonical per page
 * is what stops Search Console reporting them as duplicates.
 */

const fs = require('fs');
const path = require('path');
const { seoFor, slugs, SITE } = require('./seo-pages');

const ROOT = path.join(__dirname, '..');
const CHECK = process.argv.indexOf('--check') !== -1;

const BEGIN = '<!-- seo:begin (generated by scripts/seo-inject.js - edit scripts/seo-pages.js) -->';
const END = '<!-- seo:end -->';
const H1_BEGIN = '<!-- seo:h1 -->';
const H1_END = '<!-- /seo:h1 -->';

const H1_STYLE = '.rk-seo-h1{position:absolute;width:1px;height:1px;margin:-1px;padding:0;overflow:hidden;clip:rect(0 0 0 0);white-space:nowrap;border:0}';
const OG_ALT = 'ReKindle - a dashboard OS for Kindle and e-ink readers';

function attr(s) {
    return String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function text(s) {
    return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function json(s) {
    // Keep the payload inert inside <script>: never let a description close it.
    return JSON.stringify(s, null, 0).replace(/</g, '\\u003c').replace(/>/g, '\\u003e');
}

function structuredData(seo) {
    const org = { '@type': 'Organization', name: 'ReKindle', url: SITE + '/' };

    if (seo.slug === 'index') {
        return {
            '@context': 'https://schema.org',
            '@graph': [
                {
                    '@type': 'WebSite',
                    name: 'ReKindle',
                    alternateName: ['ReKindle.ink', 'ReKindle OS'],
                    url: SITE + '/',
                    description: seo.desc,
                    inLanguage: 'en',
                    publisher: org
                },
                {
                    '@type': 'WebApplication',
                    name: 'ReKindle',
                    url: SITE + '/',
                    applicationCategory: 'UtilitiesApplication',
                    operatingSystem: 'Kindle, Kobo, Android, iOS, web browser',
                    browserRequirements: 'Requires JavaScript',
                    isAccessibleForFree: true,
                    offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
                    description: seo.desc
                }
            ]
        };
    }

    return {
        '@context': 'https://schema.org',
        '@graph': [
            {
                '@type': 'WebApplication',
                name: seo.name,
                url: seo.canonical,
                applicationCategory: seo.category,
                operatingSystem: 'Kindle, Kobo, Android, iOS, web browser',
                browserRequirements: 'Requires JavaScript',
                isAccessibleForFree: true,
                offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
                description: seo.desc,
                inLanguage: 'en',
                isPartOf: { '@type': 'WebSite', name: 'ReKindle', url: SITE + '/' },
                publisher: org
            },
            {
                '@type': 'BreadcrumbList',
                itemListElement: [
                    { '@type': 'ListItem', position: 1, name: 'ReKindle', item: SITE + '/' },
                    { '@type': 'ListItem', position: 2, name: seo.name, item: seo.canonical }
                ]
            }
        ]
    };
}

function headBlock(seo) {
    const t = attr(seo.title);
    const d = attr(seo.desc);
    const c = attr(seo.canonical);
    const img = attr(seo.image);
    const robots = seo.noindex ? 'noindex, nofollow' : 'index, follow, max-image-preview:large';

    return [
        '    ' + BEGIN,
        '    <meta name="description" content="' + d + '">',
        '    <meta name="robots" content="' + robots + '">',
        '    <link rel="canonical" href="' + c + '">',
        '    <meta property="og:site_name" content="ReKindle">',
        '    <meta property="og:type" content="website">',
        '    <meta property="og:title" content="' + t + '">',
        '    <meta property="og:description" content="' + d + '">',
        '    <meta property="og:url" content="' + c + '">',
        '    <meta property="og:image" content="' + img + '">',
        '    <meta property="og:image:width" content="1200">',
        '    <meta property="og:image:height" content="630">',
        '    <meta property="og:image:alt" content="' + attr(OG_ALT) + '">',
        '    <meta name="twitter:card" content="summary_large_image">',
        '    <meta name="twitter:title" content="' + t + '">',
        '    <meta name="twitter:description" content="' + d + '">',
        '    <meta name="twitter:image" content="' + img + '">',
        '    <style>' + H1_STYLE + '</style>',
        '    <script type="application/ld+json">' + json(structuredData(seo)) + '</script>',
        '    ' + END
    ].join('\n');
}

/** True when the document already has a heading a reader could use. */
function hasTextHeading(html) {
    // Headings inside <script> are template strings (browser.html, help.html,
    // newspaper.html, readwise.html, rssreader.html build their articles in JS)
    // and are not part of the served document.
    const withoutScripts = html.replace(/<script\b[\s\S]*?<\/script>/gi, '');
    const re = /<h1\b[^>]*>([\s\S]*?)<\/h1>/gi;
    let m;
    while ((m = re.exec(withoutScripts))) {
        const body = m[1].replace(/<[^>]*>/g, '').replace(/&nbsp;/g, ' ').trim();
        if (body) return true;
    }
    return false;
}

function stripGenerated(html) {
    let out = html;
    const begin = out.indexOf(BEGIN);
    const end = out.indexOf(END);
    if (begin !== -1 && end > begin) {
        // Also swallow the leading indentation of the begin marker's line.
        let start = begin;
        while (start > 0 && (out[start - 1] === ' ' || out[start - 1] === '\t')) start--;
        if (out[start - 1] === '\n') start--;
        out = out.slice(0, start) + out.slice(end + END.length);
    }
    out = out.replace(/\s*<!-- seo:h1 -->[\s\S]*?<!-- \/seo:h1 -->/g, '');

    // Drop hand-written duplicates so there is exactly one of each tag. Without
    // this, the pre-existing `description` on changelog.html/kindle.html and the
    // `robots` meta on moderation.html would win over the generated block.
    out = out.replace(/^[ \t]*<meta\s+name="description"[^>]*>\s*$/gim, '');
    out = out.replace(/^[ \t]*<meta\s+name="robots"[^>]*>\s*$/gim, '');
    out = out.replace(/^[ \t]*<link\s+rel="canonical"[^>]*>\s*$/gim, '');
    out = out.replace(/^[ \t]*<meta\s+property="og:[^"]*"[^>]*>\s*$/gim, '');
    out = out.replace(/^[ \t]*<meta\s+name="twitter:[^"]*"[^>]*>\s*$/gim, '');
    return out;
}

function render(html, seo) {
    let out = stripGenerated(html);

    if (out.indexOf('</head>') === -1) throw new Error('no </head> found');

    // Rewrite the document title itself (the text Google shows in results).
    // Keep any data-i18n attribute: i18n.js only overwrites it when the active
    // locale actually has that key, so English keeps this title and other
    // languages keep their translation.
    if (/<title\b[^>]*>[\s\S]*?<\/title>/i.test(out)) {
        out = out.replace(/<title\b[^>]*>[\s\S]*?<\/title>/i, function (match) {
            const open = match.match(/<title\b[^>]*>/i)[0];
            return open + text(seo.title) + '</title>';
        });
    }

    return finalize(out, seo);
}

function finalize(out, seo) {
    const headClose = out.indexOf('</head>');
    if (headClose === -1) throw new Error('no </head> found');

    if (!/<title\b[^>]*>[\s\S]*?<\/title>/i.test(out)) {
        out = out.slice(0, headClose) + '<title>' + text(seo.title) + '</title>\n' + out.slice(headClose);
        return finalize(out, seo);
    }

    out = out.slice(0, headClose) + headBlock(seo) + '\n' + out.slice(headClose);

    if (!hasTextHeading(out)) {
        const bodyOpen = out.match(/<body[^>]*>/i);
        if (bodyOpen) {
            const at = bodyOpen.index + bodyOpen[0].length;
            const h1 = '\n    ' + H1_BEGIN + '<h1 class="rk-seo-h1">' + text(seo.h1) + '</h1>' + H1_END;
            out = out.slice(0, at) + h1 + out.slice(at);
        }
    }

    return out;
}

function main() {
    const pages = fs.readdirSync(ROOT).filter(function (f) { return f.endsWith('.html'); }).sort();
    const missing = [];
    const changed = [];

    for (const file of pages) {
        if (file === '404.html') continue; // deliberately index-free and hand-written
        const slug = file.replace(/\.html$/, '');
        const seo = seoFor(slug);
        if (!seo) { missing.push(file); continue; }

        const original = fs.readFileSync(path.join(ROOT, file), 'utf8');
        const next = render(original, seo);
        if (next !== original) {
            changed.push(file);
            if (!CHECK) fs.writeFileSync(path.join(ROOT, file), next);
        }
    }

    if (missing.length) {
        console.error('FAIL - no scripts/seo-pages.js entry for: ' + missing.join(', '));
        process.exitCode = 1;
    }

    const registered = slugs().filter(function (s) { return fs.existsSync(path.join(ROOT, s + '.html')); });
    if (registered.length !== slugs().length) {
        const gone = slugs().filter(function (s) { return !fs.existsSync(path.join(ROOT, s + '.html')); });
        console.error('FAIL - scripts/seo-pages.js lists pages that do not exist: ' + gone.join(', '));
        process.exitCode = 1;
    }

    if (CHECK) {
        if (changed.length) {
            console.error('FAIL - ' + changed.length + ' page(s) have a stale SEO block (run node scripts/seo-inject.js):');
            for (const f of changed) console.error('  ' + f);
            process.exitCode = 1;
        } else {
            console.log('PASS - SEO blocks are up to date (' + pages.length + ' pages)');
        }
        return;
    }

    console.log((process.exitCode ? 'WARN' : 'OK') + ' - updated ' + changed.length + ' of ' + pages.length + ' pages');
}

if (require.main === module) main();
module.exports = { render: render, seoFor: seoFor, headBlock: headBlock };
